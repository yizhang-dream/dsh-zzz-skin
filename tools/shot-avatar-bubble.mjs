const PORT = 9334;
const list = await (await fetch(`http://127.0.0.1:${PORT}/json/list`)).json();
const page = list.filter((t) => t.type === 'page' && !t.url.startsWith('devtools')).find((t) => t.url.includes('100.112.92.62'));
const ws = new WebSocket(page.webSocketDebuggerUrl);
await new Promise((r) => (ws.onopen = r));
let id = 0; const pending = new Map();
ws.onmessage = (e) => { const m = JSON.parse(e.data); if (m.id && pending.has(m.id)) { pending.get(m.id)(m); pending.delete(m.id); } };
const send = (m, p = {}) => new Promise((r) => { const i = ++id; pending.set(i, r); ws.send(JSON.stringify({ id: i, method: m, params: p })); });
const ev = async (f) => (await send('Runtime.evaluate', { expression: f, returnByValue: true, awaitPromise: true })).result.result.value;
await send('Page.bringToFront');
const info = await ev(`(() => new Promise(res => {
  const rows = [...document.querySelectorAll('[data-chat-anchor-key*=":assistant-step"]:not([data-chat-anchor-key*="["]):not([hidden])')];
  const short = rows.filter((el) => el.getBoundingClientRect().height < 400);
  const el = short[0] || rows[0];
  el.scrollIntoView({ block: 'center' });
  setTimeout(() => {
    const r = el.getBoundingClientRect();
    res(JSON.stringify({ x: r.x, y: r.y, w: r.width, h: r.height }));
  }, 900);
}))()`);
console.log(info);
if (info.includes('fail') || info === 'undefined') process.exit(1);
const { x, y, w, h } = JSON.parse(info);
await new Promise((r) => setTimeout(r, 250));
const shot = await send('Page.captureScreenshot', { format: 'png' });
const { writeFileSync } = await import('node:fs');
writeFileSync('build/avatar-bubble.png', Buffer.from(shot.result.data, 'base64'));
const dpr = 1.3625;
const cx = Math.max(0, Math.round((x - 10) * dpr)), cy = Math.max(0, Math.round((y - 15) * dpr));
const cw = Math.round(Math.min(500, w) * dpr), ch = Math.round(Math.min(160, h + 30) * dpr);
writeFileSync('build/avatar-bubble-crop.txt', `${cx} ${cy} ${cw} ${ch}`);
console.log('saved', `crop ${cx} ${cy} ${cw} ${ch}`);
ws.close();
